// 今天若命中纪念日，返回其中一句；否则 null——由调用方决定优先级
export const mikuDateLine = (date: Date = new Date()): string | null => {
  if (isLunarDate(6, 3, date)) {
    return MIKU_BIRTHDAY_LUNAR_LINES[Math.floor(Math.random() * MIKU_BIRTHDAY_LUNAR_LINES.length)];
  }
  const pool = MIKU_DATE_LINES[mmdd(date.getMonth() + 1, date.getDate())];
  if (!pool?.length) return null;
  return pool[Math.floor(Math.random() * pool.length)];
};
